// Auto-build the seat → panorama map from the files in public/renders/.
//
// Convention: name a render after its seat and drop it in the auditorium's
// folder — e.g. public/renders/main/A22.jpg or public/renders/chamber/g22.png
// (case-insensitive). The seat letter is upper-cased, so `g22.png` → seat G22.
// Files that aren't named after a seat (e.g. placeholder.jpg) are ignored.
//
// Runs automatically via the `predev` / `prebuild` npm scripts; run by hand
// with `npm run gen:seat-views`.

import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, parse } from 'node:path';

const ROOT = process.cwd();
const RENDERS_DIR = join(ROOT, 'public', 'renders');
const OUT_FILE = join(ROOT, 'src', 'lib', 'seatViews.generated.ts');

const IMAGE_EXTS = new Set(['.jpg', '.jpeg', '.png', '.webp']);
const SEAT_RE = /^([A-Za-z]+)(\d+)$/; // e.g. A22, g12

function listDirs(dir) {
  try {
    return readdirSync(dir).filter((name) => statSync(join(dir, name)).isDirectory());
  } catch {
    return [];
  }
}

function build() {
  const map = {};

  for (const auditorium of listDirs(RENDERS_DIR)) {
    const dir = join(RENDERS_DIR, auditorium);
    for (const file of readdirSync(dir)) {
      const { name, ext } = parse(file);
      if (!IMAGE_EXTS.has(ext.toLowerCase())) continue;

      const match = name.match(SEAT_RE);
      if (!match) continue; // not a seat-named file → skip (e.g. placeholder.jpg)

      const seatId = match[1].toUpperCase() + match[2];
      (map[auditorium] ??= {})[seatId] = `/renders/${auditorium}/${file}`;
    }
  }

  return map;
}

const map = build();

const banner =
  '// AUTO-GENERATED by scripts/generate-seat-views.mjs — do not edit by hand.\n' +
  '// Drop a panorama named after its seat (e.g. public/renders/main/G22.jpg)\n' +
  '// and re-run `npm run gen:seat-views` (runs automatically on dev/build).\n\n';

const body =
  'export const generatedSeatViews: Record<string, Record<string, string>> = ' +
  `${JSON.stringify(map, null, 2)};\n`;

writeFileSync(OUT_FILE, banner + body);

const summary = Object.entries(map)
  .map(([aud, seats]) => `  ${aud}: ${Object.keys(seats).join(', ') || '(none)'}`)
  .join('\n');
console.log(`seatViews → ${OUT_FILE}\n${summary || '  (no seat-named renders found)'}`);
